// builds the land outline used by the flight maps, run with node scripts/gen-world-dots.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoEquirectangular, geoPath } from 'd3-geo';

const LAT_TOP = 78;
const LAT_BOTTOM = -58;

const topology = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)));
const raw = feature(topology, topology.objects.land);

// antarctica sits below the map and its pole wrapping ring makes the projected path cover the oceans instead
const land = {
  type: 'MultiPolygon',
  coordinates: raw.features.flatMap(f => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates)).filter(polygon => polygon[0].some(([, lat]) => lat > -60)),
};

// one degree per unit, x runs 0 to 360 and y counts down from the top latitude, d3 cuts rings at the date line
const projection = geoEquirectangular().scale(180 / Math.PI).translate([180, LAT_TOP]);
const path = geoPath(projection).digits(1)(land);

const out = `// generated by scripts/gen-world-dots.mjs, do not edit by hand
export const WORLD_WIDTH = 360;
export const WORLD_HEIGHT = ${LAT_TOP - LAT_BOTTOM};
export const LAT_TOP = ${LAT_TOP};
export const LAND_PATH = '${path}';
`;
writeFileSync(new URL('../src/data/worldDots.ts', import.meta.url), out);
console.log(`${(out.length / 1024).toFixed(1)} kB`);
